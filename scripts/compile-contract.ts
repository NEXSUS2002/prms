// Compiles contracts/PRMSRegistry.sol with the solc package (no download needed) and writes the
// ABI and bytecode to src/chain/PRMSRegistry.json, which both the app and the deploy script import.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const solc = require("solc");
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(resolve(root, "contracts/PRMSRegistry.sol"), "utf8");

const input = {
  language: "Solidity",
  sources: { "PRMSRegistry.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "paris",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const problems = (output.errors ?? []) as Array<{ severity: string; formattedMessage: string }>;
for (const p of problems) console.log(p.formattedMessage);
if (problems.some((p) => p.severity === "error")) process.exit(1);

const contract = output.contracts["PRMSRegistry.sol"].PRMSRegistry;
mkdirSync(resolve(root, "src/chain"), { recursive: true });
writeFileSync(
  resolve(root, "src/chain/PRMSRegistry.json"),
  JSON.stringify({ contractName: "PRMSRegistry", compiler: solc.version(), abi: contract.abi, bytecode: "0x" + contract.evm.bytecode.object }, null, 2) + "\n",
);
writeFileSync(
  resolve(root, "src/chain/abi.ts"),
  "// Generated by scripts/compile-contract.ts. Do not edit by hand.\nexport const prmsAbi = " + JSON.stringify(contract.abi, null, 2) + " as const;\n",
);
console.log(`Compiled PRMSRegistry with solc ${solc.version()} (${contract.evm.bytecode.object.length / 2} bytes)`);
